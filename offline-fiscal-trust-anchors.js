function validatePinnedRoot() {
  const cert = new crypto.X509Certificate(ICP_BRASIL_V10_PEM);
  const fingerprint = String(cert.fingerprint256 || '').replace(/:/g, '').toUpperCase();
  if (fingerprint !== ICP_BRASIL_V10_SHA256) throw new Error('Fingerprint da raiz ICP-Brasil v10 não confere.');
  if (String(cert.subject) !== String(cert.issuer) || !cert.verify(cert.publicKey)) {
    throw new Error('Raiz ICP-Brasil v10 fixada não é autoassinada válida.');
  }
  const now = Date.now();
  const from = Date.parse(cert.validFrom);
  const to = Date.parse(cert.validTo);
  if (!Number.isFinite(from) || !Number.isFinite(to) || now < from || now >= to) {
    throw new Error('Raiz ICP-Brasil v10 fixada está fora da validade.');
  }
  return cert.toString();
}

const VALIDATED_ICP_BRASIL_V10_PEM = validatePinnedRoot();

function safeCaList(type) {
  try {
    if (typeof tls.getCACertificates === 'function') return tls.getCACertificates(type);
  } catch (_) {}
  return type === 'default' && Array.isArray(tls.rootCertificates) ? tls.rootCertificates : [];
}

function getSvrsTrustAnchors() {
  return [...new Set([
    ...safeCaList('default'),
    ...safeCaList('system'),
    VALIDATED_ICP_BRASIL_V10_PEM
  ])];
}

